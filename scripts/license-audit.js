import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {dirname, join, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

/**
 * Licenses that permit distribution of this application without forcing us to
 * publish our source or restricting commercial use.
 */
export const ALLOWED = new Set([
  'MIT', 'MIT-0', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0',
  'Unlicense', 'CC0-1.0', 'WTFPL', 'Zlib', 'BlueOak-1.0.0', 'PostgreSQL',
  'Python-2.0', 'CC-BY-4.0'
]);

const REVIEW_PATTERNS = [
  [/^A?GPL/i, 'strong copyleft: distributing this app would require source disclosure'],
  [/^LGPL/i, 'weak copyleft: dynamic-linking and notice obligations apply'],
  [/^SSPL/i, 'service copyleft: offering the service requires source disclosure'],
  [/^(?:BUSL|BSL)/i, 'source-available: production use is time- or scope-limited'],
  [/^CC-BY-NC/i, 'non-commercial: incompatible with commercial use'],
  [/^UNLICENSED$/i, 'no license granted'],
  [/^CC-BY-SA/i, 'share-alike: derivative distribution must use the same license']
];

// Explicit, reviewed exceptions. Add only after reading the actual license.
export const OVERRIDES = Object.freeze({});

export function normalizeLicense(license) {
  if (!license) return null;
  const value = typeof license === 'object' ? license.type : license;
  if (typeof value !== 'string') return null;
  return value.replace(/[()]/g, '').trim() || null;
}

export function classify(license, name = '') {
  if (OVERRIDES[name]) return {status: 'ok', license: OVERRIDES[name], reason: 'reviewed override'};
  const normalized = normalizeLicense(license);
  if (!normalized) return {status: 'review', license: null, reason: 'missing license declaration'};
  const primary = normalized.split(/\s+(?:OR|AND)\s+|[/,]/i)[0].trim();
  if (ALLOWED.has(normalized) || ALLOWED.has(primary)) return {status: 'ok', license: normalized};
  for (const [pattern, reason] of REVIEW_PATTERNS) {
    if (pattern.test(normalized)) return {status: 'review', license: normalized, reason};
  }
  return {status: 'review', license: normalized, reason: 'unrecognized license: verify before distributing'};
}

async function readLicenseText(directory) {
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'COPYING', 'COPYING.md']) {
    try {
      const text = await readFile(join(directory, file), 'utf8');
      if (text.trim()) return {file, text};
    } catch {}
  }
  return null;
}

export async function audit(root = process.cwd()) {
  const lock = JSON.parse(await readFile(resolve(root, 'package-lock.json'), 'utf8'));
  const packages = lock.packages ?? {};
  const results = [];
  for (const [path, meta] of Object.entries(packages)) {
    if (!path.startsWith('node_modules/') || meta.dev) continue;
    const name = meta.name ?? path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    const directory = resolve(root, path);
    let declared = meta.license;
    try {
      const manifest = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
      declared = manifest.license ?? declared;
    } catch {}
    const verdict = classify(declared, name);
    const licenseFile = await readLicenseText(directory);
    results.push({name, version: meta.version, path, ...verdict, licenseFile});
  }
  results.sort((a, b) => a.name.localeCompare(b.name));
  return results;
}

function writeReport(results, target) {
  const lines = [
    'MarketreaderPro third-party license inventory',
    'Generated by scripts/license-audit.js. Regenerate after dependency changes.',
    ''
  ];
  for (const item of results) {
    lines.push(`${item.name} ${item.version ?? ''}`.trim());
    lines.push(`  License: ${item.license ?? 'MISSING'}`);
    if (item.licenseFile) {
      lines.push(`  Text (${item.licenseFile.file}):`);
      lines.push(item.licenseFile.text.split(/\r?\n/).map(line => '    ' + line).join('\n'));
    } else {
      lines.push('  Text: not shipped in the installed package; see the upstream project.');
    }
    lines.push('');
  }
  return writeFile(target, lines.join('\n') + '\n', 'utf8');
}

export async function run({root = process.cwd(), reportPath} = {}) {
  const results = await audit(root);
  if (!results.length) throw Error('No installed production dependencies found. Run npm ci first.');
  if (reportPath) {
    await mkdir(dirname(resolve(root, reportPath)), {recursive: true});
    await writeReport(results, resolve(root, reportPath));
    console.log(`Wrote ${reportPath} (${results.length} packages).`);
  }
  const flagged = results.filter(item => item.status !== 'ok');
  for (const item of results) {
    console.log(`${item.status === 'ok' ? 'ok  ' : 'FAIL'}  ${item.name} ${item.version ?? ''} — ${item.license ?? 'missing'}`);
  }
  if (flagged.length) {
    console.error(`\nLicense audit failed for ${flagged.length} package(s):`);
    for (const item of flagged) console.error(`  ${item.name}: ${item.reason}`);
    return 1;
  }
  console.log(`\nLicense audit passed: ${results.length} production packages use permissive licenses.`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const flag = process.argv.indexOf('--report');
  const reportPath = flag === -1 ? undefined : process.argv[flag + 1];
  process.exitCode = await run({reportPath});
}
